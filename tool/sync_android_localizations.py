"""Generate native Android resources from the shared Flutter ARB catalogs."""

import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
NATIVE_KEYS = {
    "focumActive", "intentionQuestion", "voiceIdleHint", "voiceRetryHint",
    "listening", "manualMode", "voiceMode", "chooseMainReason",
    "chooseBeforeEntering", "sayBeforeEntering", "categoryLearning",
    "categoryWork", "categoryPersonalGrowth", "categorySocial", "categoryHealth",
    "categoryTravel", "categoryPersonal", "categoryOther", "focusMismatchTitle",
    "focusMismatchMessage", "returnToIntention", "fiveMinutesTitle", "keepGoing",
    "reminderPhone", "reminderApp", "reminderIntention", "reopenFocum",
    "activationReminder", "statusChannelName", "statusChannelDescription",
    "remindersChannelName", "remindersChannelDescription", "monitorChannelName",
    "monitorChannelDescription", "monitorNotification",
}


def resource_name(key):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", key).lower()


def generate():
    catalog_dir = ROOT / "lib/l10n"
    template = json.loads((catalog_dir / "app_en.arb").read_text(encoding="utf-8"))
    message_keys = {key for key in template if not key.startswith("@")}
    for source in sorted(catalog_dir.glob("app_*.arb")):
        catalog = json.loads(source.read_text(encoding="utf-8"))
        locale = catalog["@@locale"]
        if {key for key in catalog if not key.startswith("@")} != message_keys:
            raise ValueError(f"Incomplete translation catalog: {source.name}")
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            '<!-- Generated by tool/sync_android_localizations.py. Edit the ARB catalogs. -->',
            '<resources>',
        ]
        for key in sorted(NATIVE_KEYS):
            value = catalog[key]
            parameters = list(template.get("@" + key, {}).get("placeholders", {}))
            if set(re.findall(r"\{(\w+)\}", value)) != set(parameters):
                raise ValueError(f"Invalid placeholders: {locale}/{key}")
            value = value.replace("%", "%%")
            for index, parameter in enumerate(parameters, 1):
                value = value.replace("{" + parameter + "}", f"%{index}$s")
            value = escape(value).replace("'", "\\'").replace('"', '\\"')
            lines.append(f'    <string name="{resource_name(key)}">{value}</string>')
        lines.append('</resources>')
        folder = "values" if locale == "en" else f"values-{locale}"
        destination = ROOT / "android/app/src/main/res" / folder / "strings.xml"
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Generated {folder}/strings.xml ({len(NATIVE_KEYS)} messages)")


if __name__ == "__main__":
    generate()
